import { chromium } from "playwright";
import { SignJWT } from "jose";
const BASE = "https://pohonasuh.io";
const secret = new TextEncoder().encode((process.env.PA_PROD_AUTH_SECRET ?? "").replace(/^"|"$/g, ""));
const token = await new SignJWT({ userId: 1, name: "A", role: "ADMIN", level: 1 })
  .setProtectedHeader({ alg: "HS256" }).setIssuedAt().setExpirationTime("1h").sign(secret);
const browser = await chromium.launch();
const ctx = await browser.newContext();
await ctx.addCookies([{ name: "pa_session", value: token, url: BASE }]);
const page = await ctx.newPage();
await page.goto(`${BASE}/admin/pohon/beku`, { waitUntil: "networkidle" });
console.log("URL:", page.url());
await page.getByLabel("Lokasi desa").selectOption("semua");
await page.getByPlaceholder("Cari kode / nama pohon…").fill("A168");
await page.waitForTimeout(1000);
const lis = await page.locator("ul li").allInnerTexts();
console.log("items:", lis.slice(0, 5), "count:", lis.length);
const cb = await page.locator("input[type=checkbox]").count();
console.log("checkboxes:", cb);
const panel = await page.locator("ul li input[type=checkbox]").first().evaluate((el) => el.outerHTML);
console.log("panel-cb:", panel);
const roles = await page.getByRole("checkbox", { name: /A168/ }).count();
console.log("role-match:", roles);
await page.getByRole("checkbox", { name: /A168/ }).first().check();
await page.waitForTimeout(500);
const st = await page.getByRole("checkbox", { name: /A168/ }).first().isChecked();
console.log("checked:", st);
const hidden = await page.locator('input[type=hidden][name="idpohon"]').count();
console.log("hidden-idpohon:", hidden);
const teksPilih = await page.locator("text=Pilih pohon").first().innerText().catch(() => "-");
console.log("label-pilih:", teksPilih);
await browser.close();
